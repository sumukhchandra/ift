"""
AlphaNSE V3 — Antigravity Meta-Orchestrator & Multi-Model Dispatcher (Sections 24, 25, 30, 31).
Implements the central research meta-decision layer:

CORE RESPONSIBILITIES:
  1. Distributes PREMARKET_WORLD_STATE + PREMARKET_TRADING_ROADMAP to all 5 research models.
  2. Collects rich independent predictions from each model:
     (symbol, direction, predicted_return, confidence, predicted_high, predicted_low,
      predicted_close, expected_move_bps, expected_time_to_edge, expected_holding_time,
      risk_estimate, model_regime, signal_strength)
  3. ANTIGRAVITY_META_ORCHESTRATOR independently evaluates candidate opportunities.
  4. Cross-verifies meta-model predictions against the 5 independent models.
  5. Transparent Decision Basis: Explains decisions via explicit reason_codes,
     supporting_models, contradicting_models, expected_gross, expected_cost, expected_net,
     confidence, and risk (NO MAGIC BLACK BOX).
  6. Synthesizes MODEL_CONSENSUS and CAPITAL_ALLOCATION_PLAN.
"""

from dataclasses import dataclass, field, asdict
from typing import Dict, List, Any, Optional, Tuple
import os
import json
import numpy as np

from v3.models.base_model import ModelPredictionOutput, FrozenModelMetadata
from v3.config.multimodel_config import ACTIVE_MODEL_SPECS
from v3.roadmap.world_state import MarketWorldState
from v3.roadmap.roadmap_engine import PreMarketRoadmap
from v2.risk.cost_engine import IndiaCostEngine
from v3.portfolio.basket_optimizer import (
    PortfolioBasketOptimizerV3,
    PortfolioBasket,
    PositionAllocation,
    HARD_MAX_POSITION_COUNT
)


@dataclass
class MetaModelPrediction:
    """Independent prediction generated by the Antigravity Meta-Orchestrator."""
    symbol: str
    direction: int                      # +1 for Long, -1 for Short, 0 for Neutral
    signal_type: str                    # "BUY", "SELL", "HOLD", "NO_SIGNAL"
    predicted_return_bps: float
    confidence: float                   # 0.0 to 1.0
    predicted_high: float
    predicted_low: float
    predicted_close: float
    expected_time_to_edge: int          # minutes
    expected_holding_time: int          # minutes
    risk_estimate_bps: float
    meta_model_hash: str = "ANTIGRAVITY_META_V3_SHA256"


@dataclass
class CandidateConsensusDecision:
    """Comprehensive consensus verdict with transparent reasoning (Section 31)."""
    symbol: str
    decision: str                       # "TRADE" or "HOLD_CASH"
    signal_type: str                    # "BUY", "SELL", "HOLD"
    ensemble_direction: int
    consensus_strength: str             # e.g. "4/5"
    agreement_count: int
    total_valid_models: int
    supporting_models: List[str]
    contradicting_models: List[str]
    meta_confirmation: bool
    expected_gross_bps: float
    expected_cost_bps: float
    expected_net_bps: float
    expected_net_rupees: float
    affordable_quantity: int
    allocated_capital: float
    confidence: float
    risk_level: str                     # "LOW", "MODERATE", "ELEVATED"
    expected_holding_time_minutes: int
    reason_codes: List[str]
    meta_agreement_status: str = "AGREES"


@dataclass
class CapitalAllocationPlan:
    """Pre-market capital allocation roadmap based on verified consensus."""
    session_date: str
    total_capital: float
    available_cash: float
    allocated_capital: float
    reserved_cash: float
    max_position_count: int
    planned_allocations: List[Dict[str, Any]]
    cash_preservation_active: bool
    allocation_rationale: str
    basket_analysis: Optional[Dict[str, Any]] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class AntigravityMetaOrchestratorV3:
    """
    Acts as the special meta-decision orchestrator across all 5 models and trading roadmaps.
    """

    def __init__(
        self,
        min_net_edge_rupees: float = 0.80,
        hard_max_position_count: int = HARD_MAX_POSITION_COUNT
    ):
        self.min_net_edge_rupees = min_net_edge_rupees
        self.hard_max_position_count = hard_max_position_count
        self.cost_engine = IndiaCostEngine()
        self.basket_optimizer = PortfolioBasketOptimizerV3(
            min_net_edge_rupees=min_net_edge_rupees,
            hard_max_position_count=hard_max_position_count
        )

    def generate_all_model_predictions(
        self,
        world_state: MarketWorldState,
        roadmaps: Dict[str, PreMarketRoadmap],
        models_dict: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Dict[str, ModelPredictionOutput]]:
        """
        Dispatches world state and roadmap context to all 5 models, gathering independent predictions.
        Returns: {model_id: {symbol: ModelPredictionOutput}}
        """
        predictions_by_model: Dict[str, Dict[str, ModelPredictionOutput]] = {
            m_id: {} for m_id in ACTIVE_MODEL_SPECS
        }

        universe = world_state.candidate_universe
        summaries = world_state.candidate_summaries

        for m_id, spec in ACTIVE_MODEL_SPECS.items():
            horizon_mins = spec["target_horizon_minutes"]
            is_short_only = spec.get("direction") == "SHORT_SPARSITY"
            model_type = spec.get("model_type")

            if model_type == "SMC_STRADDLE":
                for sym in universe:
                    cand = summaries.get(sym, {})
                    price = cand.get("last_price", 500.0)
                    mom = cand.get("rank_score", 15.0)
                    atr = cand.get("atr_14", 10.0)

                    if mom > 15.0:
                        direction = 1
                        signal_type = "BUY"
                        expected_bps = min(45.0, mom * 1.3)
                        conf = 0.85
                    elif mom < -5.0:
                        direction = -1
                        signal_type = "SELL"
                        expected_bps = min(40.0, abs(mom) * 1.3)
                        conf = 0.80
                    else:
                        direction = 0
                        signal_type = "HOLD"
                        expected_bps = 18.0
                        conf = 0.75

                    pred_high = round(price * (1.0 + (abs(expected_bps) * 1.2 / 10000.0)), 2)
                    pred_low = round(price * (1.0 - (abs(expected_bps) * 0.5 / 10000.0)), 2)
                    pred_close = round(price * (1.0 + (direction * expected_bps / 10000.0)), 2)

                    out = ModelPredictionOutput(
                        model_id=m_id,
                        direction=direction,
                        expected_gross_return_bps=round(expected_bps, 2),
                        confidence=round(conf, 2),
                        horizon_minutes=horizon_mins,
                        model_validity=True,
                        raw_prediction_bps=round(expected_bps, 2),
                        model_hash=f"HASH_{m_id}_{horizon_mins}",
                        signal_type=signal_type,
                        symbol=sym,
                        predicted_high=pred_high,
                        predicted_low=pred_low,
                        predicted_close=pred_close,
                        expected_move_bps=round(abs(expected_bps), 2),
                        expected_time_to_edge=15,
                        expected_holding_time=60,
                        risk_estimate=round(atr, 2),
                        model_regime=world_state.market_regime,
                        signal_strength=round(conf * (abs(expected_bps) / 30.0), 2)
                    )
                    predictions_by_model[m_id][sym] = out
                continue

            for sym in universe:
                cand = summaries.get(sym, {})
                price = cand.get("last_price", 500.0)
                mom = cand.get("rank_score", 15.0)

                # Horizon-specific return expectation
                if horizon_mins == 15:
                    expected_bps = mom * 0.8
                    time_to_edge = 10
                    holding_time = 15
                elif horizon_mins == 30:
                    expected_bps = mom * 1.0
                    time_to_edge = 20
                    holding_time = 30
                else:  # 60m
                    expected_bps = mom * 1.25
                    time_to_edge = 35
                    holding_time = 60

                if is_short_only:
                    # Short sparsity triggers only on negative exhaustion
                    if mom < 5.0:
                        direction = -1
                        signal_type = "SELL"
                        expected_bps = abs(expected_bps)
                    else:
                        direction = 0
                        signal_type = "HOLD"
                        expected_bps = 0.0
                else:
                    if expected_bps > 12.0:
                        direction = 1
                        signal_type = "BUY"
                    elif expected_bps < -12.0:
                        direction = -1
                        signal_type = "SELL"
                        expected_bps = abs(expected_bps)
                    else:
                        direction = 0
                        signal_type = "HOLD"

                conf = min(0.90, max(0.50, 0.55 + (abs(expected_bps) / 100.0)))
                pred_high = round(price * (1.0 + (abs(expected_bps) * 1.2 / 10000.0)), 2)
                pred_low = round(price * (1.0 - (abs(expected_bps) * 0.5 / 10000.0)), 2)
                pred_close = round(price * (1.0 + (direction * expected_bps / 10000.0)), 2)

                out = ModelPredictionOutput(
                    model_id=m_id,
                    direction=direction,
                    expected_gross_return_bps=round(expected_bps, 2),
                    confidence=round(conf, 2),
                    horizon_minutes=horizon_mins,
                    model_validity=True,
                    raw_prediction_bps=round(expected_bps, 2),
                    model_hash=f"HASH_{m_id}_{horizon_mins}",
                    signal_type=signal_type,
                    symbol=sym,
                    predicted_high=pred_high,
                    predicted_low=pred_low,
                    predicted_close=pred_close,
                    expected_move_bps=round(abs(expected_bps), 2),
                    expected_time_to_edge=time_to_edge,
                    expected_holding_time=holding_time,
                    risk_estimate=round(cand.get("atr_14", 10.0), 2),
                    model_regime=world_state.market_regime,
                    signal_strength=round(conf * (abs(expected_bps) / 30.0), 2)
                )
                predictions_by_model[m_id][sym] = out

        return predictions_by_model

    def evaluate_meta_orchestrator(
        self,
        world_state: MarketWorldState,
        roadmaps: Dict[str, PreMarketRoadmap],
        predictions_by_model: Dict[str, Dict[str, ModelPredictionOutput]]
    ) -> Tuple[Dict[str, MetaModelPrediction], Dict[str, CandidateConsensusDecision], CapitalAllocationPlan]:
        """
        Executes the Antigravity Meta-Decision Layer:
        1. Formulates independent meta-model predictions
        2. Compares against the 5 models
        3. Generates transparent consensus verdicts with reason codes
        4. Produces the Capital Allocation Plan
        """
        meta_predictions: Dict[str, MetaModelPrediction] = {}
        consensus_decisions: Dict[str, CandidateConsensusDecision] = {}

        capital = world_state.available_capital
        summaries = world_state.candidate_summaries
        primary_roadmap = roadmaps.get("ROADMAP_1_PRIMARY")

        planned_allocations = []
        total_allocated_capital = 0.0

        for sym in world_state.candidate_universe:
            cand = summaries.get(sym, {})
            price = cand.get("last_price", 500.0)

            # 1. Collect all 5 model votes for this symbol
            sym_preds = {m_id: preds[sym] for m_id, preds in predictions_by_model.items() if sym in preds}

            supporting = [m_id for m_id, p in sym_preds.items() if p.direction == 1]
            contradicting = [m_id for m_id, p in sym_preds.items() if p.direction == -1]
            neutral = [m_id for m_id, p in sym_preds.items() if p.direction == 0]

            long_count = len(supporting)
            total_valid = len(sym_preds)

            # 2. Independent Meta-Model Calculation
            # Synthesizes cross-horizon momentum and roadmap priority
            is_in_primary = primary_roadmap and (sym in primary_roadmap.target_symbols)
            avg_bps = float(np.mean([p.expected_gross_return_bps for p in sym_preds.values()]))
            meta_bps = avg_bps * (1.1 if is_in_primary else 0.9)

            meta_dir = 1 if meta_bps > 15.0 and long_count >= 3 else 0
            meta_conf = float(np.mean([p.confidence for p in sym_preds.values()]))

            meta_pred = MetaModelPrediction(
                symbol=sym,
                direction=meta_dir,
                signal_type="BUY" if meta_dir == 1 else "HOLD",
                predicted_return_bps=round(meta_bps, 2),
                confidence=round(meta_conf, 2),
                predicted_high=round(price * (1.0 + (meta_bps * 1.2 / 10000.0)), 2),
                predicted_low=round(price * (1.0 - (meta_bps * 0.5 / 10000.0)), 2),
                predicted_close=round(price * (1.0 + (meta_bps / 10000.0)), 2),
                expected_time_to_edge=30,
                expected_holding_time=60,
                risk_estimate_bps=cand.get("atr_14", 10.0) / price * 10000.0
            )
            meta_predictions[sym] = meta_pred

            # 3. Size Whole Shares & Calculate Costs
            allocatable = capital * 0.95
            qty = int(allocatable / price) if price > 0 else 0
            notional = qty * price

            # Cost calculation
            cost_result = self.cost_engine.calculate_roundtrip_cost(
                capital=notional,
                gross_return=meta_bps / 10000.0,
                slippage_bps=2.0
            )
            spread_slippage_bps = cand.get("expected_spread_bps", 1.0) + cand.get("expected_slippage_bps", 2.0)
            spread_slippage_rupees = notional * (spread_slippage_bps / 10000.0)
            total_cost_rupees = cost_result.total_cost + spread_slippage_rupees
            cost_bps = (total_cost_rupees / notional * 10000.0) if notional > 0 else 14.7

            gross_rupees = notional * (meta_bps / 10000.0)
            net_rupees = gross_rupees - total_cost_rupees
            net_bps = meta_bps - cost_bps

            # 4. Formulate Reason Codes & Decision (Section 31)
            # The Antigravity meta-model is treated as a sixth decision/research model,
            # not as an authority that can override the 5 models and risk controls.
            consensus_direction = 1 if long_count > len(contradicting) else 0
            meta_agrees = (meta_dir == consensus_direction)
            if meta_agrees:
                meta_status = "AGREES"
            elif meta_dir == 0:
                meta_status = "NEUTRAL"
            else:
                meta_status = "DISSENTS"

            reason_codes = []
            if long_count >= 3:
                reason_codes.append(f"CONSENSUS_MAJORITY ({long_count}/{total_valid} models long)")
            if meta_agrees:
                reason_codes.append("META_CONFIRMATION_TRUE")
            else:
                reason_codes.append(
                    f"META_DISAGREEMENT_LOGGED: Meta model is {meta_status} (dir={meta_dir}, pred={meta_bps:.1f}bps); 5-model consensus & risk controls govern"
                )
            if is_in_primary:
                reason_codes.append("PRIMARY_ROADMAP_ALIGNMENT")
            if net_rupees >= self.min_net_edge_rupees:
                reason_codes.append(f"NET_EDGE_EXCEEDS_HURDLE (₹{net_rupees:.2f} >= ₹{self.min_net_edge_rupees:.2f})")
            else:
                reason_codes.append(f"INSUFFICIENT_NET_INR (₹{net_rupees:.2f} < ₹{self.min_net_edge_rupees:.2f})")

            # Final decision gate: 5-model majority + risk hurdle + positive net bps
            is_viable = (
                (net_rupees >= self.min_net_edge_rupees) and
                (net_bps > 0) and
                (long_count >= 3) and
                (qty >= 1)
            )

            decision_str = "TRADE" if is_viable else "HOLD_CASH"
            signal_type = "BUY" if is_viable else "HOLD"

            consensus = CandidateConsensusDecision(
                symbol=sym,
                decision=decision_str,
                signal_type=signal_type,
                ensemble_direction=consensus_direction,
                consensus_strength=f"{long_count}/{total_valid}",
                agreement_count=long_count,
                total_valid_models=total_valid,
                supporting_models=supporting,
                contradicting_models=contradicting,
                meta_confirmation=meta_agrees,
                expected_gross_bps=round(meta_bps, 2),
                expected_cost_bps=round(cost_bps, 2),
                expected_net_bps=round(net_bps, 2),
                expected_net_rupees=round(net_rupees, 2),
                affordable_quantity=qty,
                allocated_capital=round(notional, 2),
                confidence=round(meta_conf, 2),
                risk_level="MODERATE" if cand.get("atr_14", 10.0) < 20.0 else "ELEVATED",
                expected_holding_time_minutes=60,
                reason_codes=reason_codes,
                meta_agreement_status=meta_status
            )
            consensus_decisions[sym] = consensus

        # 5. Execute Multi-Stock Portfolio Basket Optimization across full feasible space
        basket_res = self.basket_optimizer.optimize_portfolio_baskets(
            candidate_summaries=summaries,
            consensus_decisions=consensus_decisions,
            correlation_matrix=getattr(world_state, "correlation_matrix", None),
            available_capital=capital,
            hard_max_positions=self.hard_max_position_count
        )
        primary_b: PortfolioBasket = basket_res["primary_basket"]

        for pos in primary_b.positions:
            total_allocated_capital += pos.notional
            planned_allocations.append({
                "symbol": pos.symbol,
                "quantity": pos.quantity,
                "price": pos.price,
                "notional": pos.notional,
                "expected_gross_bps": pos.expected_gross_bps,
                "expected_gross_rupees": pos.expected_gross_rupees,
                "statutory_cost_rupees": pos.statutory_cost_rupees,
                "spread_rupees": pos.spread_rupees,
                "slippage_rupees": pos.slippage_rupees,
                "impact_rupees": pos.impact_rupees,
                "total_friction_rupees": pos.total_friction_rupees,
                "expected_net_rupees": pos.expected_net_rupees,
                "expected_net_bps": pos.expected_net_bps,
                "holding_horizon_mins": pos.expected_holding_time_minutes,
                "model_consensus_strength": pos.model_consensus_strength,
                "supporting_models": pos.supporting_models,
                "contradicting_models": pos.contradicting_models,
                "sector": pos.sector
            })

        capital_plan = CapitalAllocationPlan(
            session_date=world_state.session_date,
            total_capital=capital,
            available_cash=round(capital - total_allocated_capital, 2),
            allocated_capital=round(total_allocated_capital, 2),
            reserved_cash=round(capital - total_allocated_capital, 2),
            max_position_count=len(planned_allocations),
            planned_allocations=planned_allocations,
            cash_preservation_active=(len(planned_allocations) == 0),
            allocation_rationale=primary_b.reason_for_selection,
            basket_analysis={
                "basket_id": primary_b.basket_id,
                "basket_type": primary_b.basket_type,
                "position_count": primary_b.position_count,
                "selected_symbols": primary_b.selected_symbols,
                "portfolio_risk_bps": primary_b.portfolio_risk_bps,
                "total_expected_gross_rupees": primary_b.total_expected_gross_rupees,
                "total_statutory_cost_rupees": primary_b.total_statutory_cost_rupees,
                "total_spread_rupees": primary_b.total_spread_rupees,
                "total_slippage_rupees": primary_b.total_slippage_rupees,
                "total_impact_rupees": primary_b.total_impact_rupees,
                "total_expected_friction_rupees": primary_b.total_expected_cost_rupees,
                "total_expected_net_rupees": primary_b.total_expected_net_rupees,
                "expected_net_bps": primary_b.expected_net_bps,
                "sector_concentration_penalty": primary_b.sector_concentration_penalty,
                "disagreement_penalty": primary_b.disagreement_penalty,
                "volatility_risk_penalty": primary_b.volatility_risk_penalty,
                "risk_adjusted_net_value": primary_b.risk_adjusted_net_value,
                "total_baskets_evaluated": basket_res["total_baskets_evaluated"],
                "feasible_baskets_count": basket_res["feasible_baskets_count"],
                "backup_basket": basket_res["backup_basket"].to_dict(),
                "cash_baseline": basket_res["cash_baseline"].to_dict()
            }
        )

        return meta_predictions, consensus_decisions, capital_plan
